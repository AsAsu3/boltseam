/**
 * Organ Router — dispatches sub-claims from a frozen Worklist to registered
 * organs by domain tag.
 *
 * Guarantees (per requirements 1.1–1.5):
 * - Each sub-claim dispatched to exactly one organ (by domain tag).
 * - Unknown domain → unverifiable/no_organ packet, never dropped.
 * - All organ calls run concurrently; Promise.allSettled semantics.
 * - Per-organ timeout: 10 seconds (configurable via options).
 * - Rejected organ promise → source_error packet; never crashes the audit.
 * - Per-sub-claim status events emitted via the onStatus callback.
 */

import type { Worklist, SubClaim } from "../intake/types.ts";
import type {
  Organ,
  OrganContext,
  EvidencePacket,
  Provenance,
} from "../organs/contract/index.ts";
import { SessionCache } from "../organs/contract/index.ts";

// ── Sub-claim status ───────────────────────────────────────────────────────

export type SubClaimStatus = "queued" | "running" | "done" | "source_error";

export interface StatusEvent {
  subClaimId: string;
  status: SubClaimStatus;
}

// ── Router options ─────────────────────────────────────────────────────────

export interface RouterOptions {
  /** Per-organ timeout in milliseconds (default: 10_000) */
  timeoutMs?: number;
  /** Callback invoked on each status change */
  onStatus?: (event: StatusEvent) => void;
  /** Anchor date for this audit (ISO-8601, defaults to now) */
  anchorDate?: string;
  /** Session cache (shared across a single audit; created if not provided) */
  cache?: SessionCache;
}

// ── Router ─────────────────────────────────────────────────────────────────

export class Router {
  private readonly _organs = new Map<string, Organ>();
  private readonly _timeoutMs: number;

  constructor(timeoutMs = 10_000) {
    this._timeoutMs = timeoutMs;
  }

  /** Register an organ. Only one organ per domain tag is permitted. */
  register(organ: Organ): this {
    this._organs.set(organ.domain, organ);
    return this;
  }

  /**
   * Dispatch all sub-claims in the worklist concurrently and return a
   * packet for every sub-claim (no sub-claim is ever dropped).
   */
  async dispatch(
    worklist: Readonly<Worklist>,
    options: RouterOptions = {},
  ): Promise<EvidencePacket[]> {
    const {
      timeoutMs = this._timeoutMs,
      onStatus,
      anchorDate = new Date().toISOString().slice(0, 10) + "T00:00:00Z",
      cache = new SessionCache(),
    } = options;

    const emit = onStatus ?? (() => undefined);

    const tasks = worklist.subClaims.map((sc) => {
      emit({ subClaimId: sc.id, status: "queued" });
      return this._dispatchOne(sc, { anchorDate, cache }, timeoutMs, emit);
    });

    return Promise.all(tasks);
  }

  // ── Internal ────────────────────────────────────────────────────────────

  private async _dispatchOne(
    sc: SubClaim,
    baseCtx: Omit<OrganContext, "signal">,
    timeoutMs: number,
    emit: (e: StatusEvent) => void,
  ): Promise<EvidencePacket> {
    const organ = this._organs.get(sc.domain);

    if (organ === undefined) {
      // No organ for this domain — return unverifiable/no_organ immediately
      emit({ subClaimId: sc.id, status: "done" });
      return noOrganPacket(sc);
    }

    emit({ subClaimId: sc.id, status: "running" });

    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), timeoutMs);

    try {
      const ctx: OrganContext = { ...baseCtx, signal: controller.signal };
      const packet = await Promise.race([
        organ.verify(sc, ctx),
        timeoutPromise(timeoutMs, sc.id),
      ]);
      emit({ subClaimId: sc.id, status: "done" });
      return packet;
    } catch (err) {
      const isTimeout =
        err instanceof Error && err.message.startsWith("organ-timeout:");
      emit({ subClaimId: sc.id, status: "source_error" });
      return errorPacket(sc, organ.domain, isTimeout ? "timeout" : "http_error", err);
    } finally {
      clearTimeout(timer);
    }
  }
}

// ── Packet factories ───────────────────────────────────────────────────────

function stubProvenance(subClaimId: string): Provenance {
  return {
    source: "router",
    requestUrl: `boltseam://router/${subClaimId}`,
    fetchedAt: new Date().toISOString().replace(/\.\d+Z$/, "Z"),
    rawExcerpt: "",
    rawSha256: null,
    rawSha256NullReason: "no source fetch; generated by the router",
  };
}

function noOrganPacket(sc: SubClaim): EvidencePacket {
  return {
    subClaimId: sc.id,
    organ: "router",
    verdict: "unverifiable",
    reason: "no_organ",
    claimedValue: sc.statedValue,
    observedValue: null,
    unit: sc.unit,
    tolerance: null,
    notes: [],
    provenance: stubProvenance(sc.id),
  };
}

function errorPacket(
  sc: SubClaim,
  organName: string,
  reason: "timeout" | "http_error",
  _err: unknown,
): EvidencePacket {
  return {
    subClaimId: sc.id,
    organ: organName,
    verdict: "source_error",
    reason,
    claimedValue: sc.statedValue,
    observedValue: null,
    unit: sc.unit,
    tolerance: null,
    notes: [],
    provenance: stubProvenance(sc.id),
  };
}

/** A promise that rejects after `ms` milliseconds with a sentinel error. */
function timeoutPromise(ms: number, subClaimId: string): Promise<never> {
  return new Promise((_, reject) =>
    setTimeout(
      () => reject(new Error(`organ-timeout:${subClaimId}`)),
      ms,
    ),
  );
}
